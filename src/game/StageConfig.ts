export function getGroundHeightAt(stage: StageSpec, x: number, z: number): number {
  let maxH = 0;
  for (const p of stage.platforms) {
    if (x >= p.minX && x <= p.maxX && z >= p.minZ && z <= p.maxZ) {
      if (p.height > maxH) maxH = p.height;
    }
  }
  return maxH;
}
